#!/usr/bin/env python3
"""Builds Sources/LiveAirspaceKit/AirportData.swift (JSON embedded as a string, so no bundle resources are needed in the app or the saver) from the OurAirports CSV (public domain).
Usage: make_airports.py path/to/airports.csv
Keeps large airports and medium airports with scheduled service and an IATA code."""
import csv, json, os, sys
rows = []
for r in csv.DictReader(open(sys.argv[1], encoding="utf-8")):
    t = r["type"]
    if t == "large_airport" or (t == "medium_airport" and r["scheduled_service"] == "yes" and r["iata_code"]):
        rows.append([r["iata_code"] or r["ident"], r["ident"], r["name"], round(float(r["latitude_deg"]), 4),
                     round(float(r["longitude_deg"]), 4), 1 if t == "large_airport" else 2])
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Sources", "LiveAirspaceKit", "AirportData.swift")
payload = json.dumps(rows, separators=(",", ":"), ensure_ascii=False)
assert '"#' not in payload
open(out, "w", encoding="utf-8").write("// Generated by Tools/make_airports.py from OurAirports (public domain). Do not edit.\n// Row: [IATA-or-ident, ICAO ident, name, lat, lon, 1=large 2=medium]\nenum AirportData {\n    static let json = #\"" + payload + "\"#\n}\n")
print(len(rows), "airports ->", os.path.getsize(out) // 1024, "KB")
